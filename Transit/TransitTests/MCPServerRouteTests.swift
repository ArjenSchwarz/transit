#if os(macOS)
import Foundation
import HTTPTypes
import Testing
@testable import Transit

/// Regression tests for T-1835: the advertised MCP Streamable HTTP endpoint
/// must distinguish an unsupported method on `/mcp` from an unknown route.
///
/// MCP 2025-03-26 requires GET on the MCP endpoint to return 405 when the
/// server does not offer an SSE listening stream. Hummingbird's unmatched
/// route fallback previously returned 404 because only POST was registered.
@MainActor @Suite(.serialized)
struct MCPServerRouteTests {

    @Test func getMcpReturnsMethodNotAllowedWithPostAllowHeader() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .get,
            path: "/mcp"
        )

        #expect(response.status == .methodNotAllowed)
        #expect(response.allow == "POST")
    }

    @Test func postMcpStillDispatchesNormally() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .post,
            path: "/mcp",
            body: #"{"jsonrpc":"2.0","id":1,"method":"ping"}"#
        )

        #expect(response.status == .ok)
    }

    @Test func getMcpStillValidatesUntrustedOrigins() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .get,
            path: "/mcp",
            origin: "https://evil.example.com"
        )

        #expect(response.status == .forbidden)
    }

    @Test func getMcpStillValidatesNonLoopbackHost() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .get,
            path: "/mcp",
            host: "rebind.example.com:3141"
        )

        #expect(response.status == .forbidden)
    }

    @Test func headMcpRemainsNotFoundWithoutAutoGeneratedHeadRoute() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .head,
            path: "/mcp"
        )

        #expect(response.status == .notFound)
        #expect(response.allow == nil)
    }

    @Test func optionsMcpRemainsNotFoundWithoutExplicitOptionsRoute() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .options,
            path: "/mcp"
        )

        #expect(response.status == .notFound)
        #expect(response.allow == nil)
    }

    @Test func getOnUnrelatedPathRemainsNotFound() async throws {
        let env = try MCPTestHelpers.makeEnv()
        let response = try await respond(
            handler: env.handler,
            method: .get,
            path: "/not-mcp"
        )

        #expect(response.status == .notFound)
        #expect(response.allow == nil)
    }

    private func respond(
        handler: MCPToolHandler,
        method: HTTPRequest.Method,
        path: String,
        origin: String? = nil,
        host: String = "127.0.0.1:3141",
        body: String = ""
    ) async throws -> MCPHTTPTestResponse {
        try await MCPTestHelpers.respond(
            handler: handler,
            method: method,
            path: path,
            origin: origin,
            authority: host,
            body: body,
            loggerLabel: "mcp-route-tests"
        )
    }
}

#endif
